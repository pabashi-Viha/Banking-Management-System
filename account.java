    public void autoID() {
   
    try {
        Class.forName("com.mysql.jdbc.Driver");
        con = DriverManager.getConnection("jdbc:mysql://localhost/finance", "root", "");
        Statement s = con.createStatement();
        ResultSet rs = s.executeQuery("SELECT MAX(Account_id) AS id FROM accout");
        rs.next();
        if (rs.getString("id") == null) {
            txtacc.setText("AC001");
        } else {
            long id = Long.parseLong(rs.getString("id").substring(2));
            id++;
            txtacc.setText("AC" + String.format("%03d", id));
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "ID Error: " + e.getMessage());
    }
}

    
    public void loadAccountType() {
    try {
        Class.forName("com.mysql.jdbc.Driver");
        con = DriverManager.getConnection("jdbc:mysql://localhost/finance", "root", "");
        insert = con.prepareStatement("SELECT * FROM accounttype");
        ResultSet rs = insert.executeQuery();
        
        txtacctype.removeAllItems();
        
        while (rs.next()) {
            txtacctype.addItem(rs.getString("Account Type")); 
        }
    } catch (Exception e) {
        System.out.println("Error loading Account Types: " + e.getMessage());
    }
}
    
    
    
