    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed
        try {
        String custid = txtcustid.getText();

        Class.forName("com.mysql.jdbc.Driver");
        con = DriverManager.getConnection("jdbc:mysql://localhost/finance", "root", "");
        insert = con.prepareStatement("select * from `customer details` where Customer_id = ?");
        insert.setString(1, custid);
        ResultSet rs = insert.executeQuery();

        if (rs.next() == false) {
            JOptionPane.showMessageDialog(this, "Customer ID not found");
        } else {
            String firstname = rs.getString("FirstName");
            String lastname = rs.getString("LastName");
            
            txtname.setText(firstname.trim() + " " + lastname.trim());
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnfindActionPerformed


