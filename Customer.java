   public void autoID() {
    try {
        Class.forName("com.mysql.jdbc.Driver");
        con = DriverManager.getConnection("jdbc:mysql://localhost/finance", "root", "");
        Statement s = con.createStatement();
        
        ResultSet rs = s.executeQuery("SELECT MAX(Customer_id) AS id FROM `customer details` ");
        rs.next();
        
        if (rs.getString("id") == null) {
            txtid.setText("CS001");
        } else {
            String idVal = rs.getString("id");
            long id = Long.parseLong(idVal.substring(2));
            id++;
            txtid.setText("CS" + String.format("%03d", id));
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "ID Error: " + e.getMessage());
    }
}
    
    public void loadBranch() {
    try {
        Class.forName("com.mysql.jdbc.Driver");
        con = DriverManager.getConnection("jdbc:mysql://localhost/finance", "root", "");
        insert = con.prepareStatement("SELECT * FROM branch");
        ResultSet rs = insert.executeQuery();
        
        txtbranch.removeAllItems();
        
        while (rs.next()) {
            txtbranch.addItem(rs.getString("Branch")); 
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Branch Error: " + e.getMessage());
    }
}
    
    
    
    
    
