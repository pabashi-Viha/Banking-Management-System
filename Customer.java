    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
 try {
    String custid = txtid.getText();
    String fname = txtfname.getText();
    String lname = txtlname.getText();
    String email = txtemail.getText();
    String branch = txtbranch.getSelectedItem().toString();
    String street = txtstreet.getText();
    String city = txtcity.getText();
    String phone = txtphone.getText();

    if (fname.isEmpty() || lname.isEmpty() || email.isEmpty() || phone.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all details!");
    } else {
        Class.forName("com.mysql.jdbc.Driver");
        con = DriverManager.getConnection("jdbc:mysql://localhost/finance", "root", "");
        
        insert = con.prepareStatement("insert into `customer details`(Customer_id, FirstName, LastName, Email, Branch, Street, City, `Phone Number`) values(?,?,?,?,?,?,?,?)");
        
        insert.setString(1, custid);
        insert.setString(2, fname);
        insert.setString(3, lname);
        insert.setString(4, email);
        insert.setString(5, branch);
        insert.setString(6, street);
        insert.setString(7, city);
        insert.setString(8, phone);
        
        insert.executeUpdate();
        
        JOptionPane.showMessageDialog(this, "Customer Added Successfully!");
        
        txtfname.setText("");
        txtlname.setText("");
        txtemail.setText("");
        txtstreet.setText("");
        txtcity.setText("");
        txtphone.setText("");
        txtfname.requestFocus();
        
        autoID(); 
    }
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}
                
        
        
    }//GEN-LAST:event_btnAddActionPerformed

